def export_corpus_manifest(output_path: Path | None = None) -> dict[str, Any]:
    entries = [c.to_dict() for c in API_CAPABILITIES]
    body = {
        "corpus_version": CORPUS_VERSION,
        "retrieval_date": RETRIEVAL_DATE,
        "total_capabilities": len(entries),
        "supported_count": sum(1 for c in API_CAPABILITIES if c.disposition == "supported"),
        "excluded_count": sum(1 for c in API_CAPABILITIES if c.disposition == "excluded"),
        "capabilities": entries,
    }
    digest = hashlib.sha256(json.dumps(body, sort_keys=True, separators=(",", ":")).encode("utf-8")).hexdigest()
    body["corpus_sha256"] = digest
    if output_path is not None:
        output_path.parent.mkdir(parents=True, exist_ok=True)
        output_path.write_text(json.dumps(body, indent=2), encoding="utf-8")
    return body
