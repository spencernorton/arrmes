@dataclass(frozen=True)
class ApiCapabilityEntry:
    capability_id: str
    service: str
    service_version: str
    source_url: str
    retrieval_date: str
    method: str
    endpoint: str
    auth_behavior: str
    parameters_schema: dict[str, Any]
    response_schema: dict[str, Any]
    error_responses: dict[str, str]
    pagination: str
    async_behavior: str
    preconditions: tuple[str, ...]
    side_effects: str
    failure_modes: tuple[str, ...]
    business_rules: tuple[str, ...]
    disposition: str  # "supported" | "deferred" | "excluded"
    arrmes_action: str | None
    required_permission: str | None
    adapter_entrypoint: str | None
    sandbox_verification_test: str

    @property
    def content_hash(self) -> str:
        payload = {
            "capability_id": self.capability_id,
            "service": self.service,
            "service_version": self.service_version,
            "source_url": self.source_url,
            "method": self.method,
            "endpoint": self.endpoint,
            "parameters_schema": self.parameters_schema,
            "response_schema": self.response_schema,
            "disposition": self.disposition,
            "arrmes_action": self.arrmes_action,
        }
        return hashlib.sha256(json.dumps(payload, sort_keys=True, separators=(",", ":")).encode("utf-8")).hexdigest()

    def to_dict(self) -> dict[str, Any]:
        d = asdict(self)
        d["content_hash"] = self.content_hash
        return d


